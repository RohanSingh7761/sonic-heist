// Bakes the web's animated SVG sprites into PNG sheets for React Native, which can't run the SVGs' CSS keyframes.
// Run from app/: node scripts/gen-sprites.mjs  (re-run after scripts/gen-sprites.mjs regenerates the SVGs)
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(APP, '../apps/web/public/sprites');
const OUT = join(APP, 'assets/sprites');
const SCALE = 6; // art pixels -> PNG pixels; big enough that hero sprites never upscale on a phone
const COLS = 4;
// Preview-only art the app never shows (see docs/ASSETS.md "Not used by the app UI").
const SKIP = new Set(['scenes/table-idle', 'scenes/heist-thief-view', 'scenes/run-all', 'props/stack-0']);

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith('.svg') ? [p] : [];
});

// Splits one flipbook SVG into its unique frames and the play order with per-frame ms.
export function parse(svg) {
  const [, w, h] = svg.match(/viewBox="0 0 (\d+) (\d+)"/).map(Number);
  const uses = [...svg.matchAll(/<use href="#([^"]+)" class="[^"]*" style="animation-name:[^;]*-k(\d+);/g)];
  if (uses.length === 0) return { w, h, frames: [null], seq: [[0, 0]], total: 0 }; // still image
  const frames = [...new Set(uses.map((u) => u[1]))];
  const seq = uses.map((u) => [frames.indexOf(u[1]), Number(u[2])]);
  const total = Number(svg.match(/animation-duration:(\d+)ms/)[1]);
  return { w, h, frames, seq, total };
}

// One static SVG with every unique frame laid out on a grid, nothing hidden.
function sheet(svg, { w, h, frames }) {
  if (frames[0] === null) return svg.replace(/^(<svg[^>]*?) width="\d+" height="\d+"/, '$1'); // scale from viewBox, not the 4x display size
  const cols = Math.min(COLS, frames.length);
  const rows = Math.ceil(frames.length / cols);
  const defs = svg.slice(svg.indexOf('<defs>'), svg.lastIndexOf('</defs>') + '</defs>'.length);
  const cells = frames.map((id, i) => `<use href="#${id}" x="${(i % cols) * w}" y="${Math.floor(i / cols) * h}"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${cols * w} ${rows * h}" shape-rendering="crispEdges">${defs}${cells}</svg>`;
}

rmSync(OUT, { recursive: true, force: true });
const entries = [];
for (const file of walk(SRC).sort()) {
  const key = relative(SRC, file).replace(/\\/g, '/').replace(/\.svg$/, '');
  if (SKIP.has(key)) continue;
  const svg = readFileSync(file, 'utf8');
  const info = parse(svg);
  // Self-check: the frame times must add up to the SVG's own loop length, or the RN animation drifts.
  assert.ok(info.frames.length >= 1, `${key}: no frames`);
  if (info.total) assert.equal(info.seq.reduce((a, [, ms]) => a + ms, 0), info.total, `${key}: frame times != loop length`);
  const png = new Resvg(sheet(svg, info), { fitTo: { mode: 'zoom', value: SCALE }, shapeRendering: 0 }).render().asPng();
  mkdirSync(dirname(join(OUT, `${key}.png`)), { recursive: true });
  writeFileSync(join(OUT, `${key}.png`), png);
  entries.push({ key, w: info.w, h: info.h, cols: Math.min(COLS, info.frames.length), seq: info.seq });
}

// Every avatar must have every state at every level, since screens pick them by name.
const STATES = ['idle', 'seated', 'sneak', 'thief', 'run', 'thief-run', 'swag', 'cry', 'caught', 'saved', 'alert', 'hunt', 'locked'];
for (const a of ['juno', 'rocco', 'nib']) for (const l of [1, 2, 3]) for (const st of STATES) {
  assert.ok(entries.some((e) => e.key === `${a}/lv${l}/${st}`), `missing ${a}/lv${l}/${st}`);
}

const body = entries
  .map((e) => `  '${e.key}': { src: require('../../assets/sprites/${e.key}.png'), w: ${e.w}, h: ${e.h}, cols: ${e.cols}, seq: ${JSON.stringify(e.seq)} },`)
  .join('\n');
writeFileSync(join(APP, 'src/ui/sprites.gen.ts'), `// Generated by app/scripts/gen-sprites.mjs. Do not edit by hand.
// seq: [frame index on the sheet, ms to show it]. A single [0, 0] entry is a still image.
export interface Sheet { src: number; w: number; h: number; cols: number; seq: [number, number][] }
export const SHEETS: Record<string, Sheet> = {
${body}
};
`);
console.log(`Baked ${entries.length} sprite sheets into assets/sprites`);
